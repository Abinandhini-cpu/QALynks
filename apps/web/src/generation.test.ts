import { describe, expect, it } from 'vitest';
import type { GeneratedCase } from '@qalynks/shared';
import { REVIEW_COLUMNS, splitLines, toTestCaseInput, validateGenerated } from './generation';

const base: GeneratedCase = {
  key: 'k',
  module: ' Billing ',
  summary: ' Pay by card ',
  steps: [' Open checkout ', 'Pay'],
  testData: ' Card: [Not specified: test card] ',
  expectedResult: ' Payment succeeds ',
  actualResult: 'should be ignored',
  scenarioType: 'negative',
  priority: 'High',
  testType: 'Integration',
  sourceReference: 'Pay by card',
  flags: {
    moduleNeedsReview: false,
    expectedResultNeedsClarification: false,
    clarificationNote: '',
    possibleDuplicateOf: [],
  },
};

describe('REVIEW_COLUMNS', () => {
  it('lists the seven required columns in order', () => {
    expect([...REVIEW_COLUMNS]).toEqual([
      'TC ID',
      'Module',
      'Summary',
      'Steps',
      'Test Data',
      'Expected Result',
      'Actual Result',
    ]);
  });
});

describe('toTestCaseInput', () => {
  it('maps the seven columns onto the existing test case model', () => {
    const input = toTestCaseInput(base);
    expect(input).toMatchObject({
      title: 'Pay by card',
      module: 'Billing',
      steps: [
        { action: 'Open checkout', expectedResult: '' },
        { action: 'Pay', expectedResult: '' },
      ],
      testData: 'Card: [Not specified: test card]',
      expectedResult: 'Payment succeeds',
      actualResult: '',
      priority: 'High',
      testType: 'Integration',
      status: 'Draft',
      tags: ['ai-generated', 'negative'],
    });
    expect(input).not.toHaveProperty('code');
  });

  it('records the source and any open clarification in the description', () => {
    const description = toTestCaseInput({
      ...base,
      flags: {
        ...base.flags,
        expectedResultNeedsClarification: true,
        clarificationNote: 'Limit unknown',
      },
    }).description;
    expect(description).toContain('Generated by AI');
    expect(description).toContain('Source: Pay by card');
    expect(description).toContain('Needs clarification: Limit unknown');
  });

  it('omits the source line when there is none', () => {
    expect(toTestCaseInput({ ...base, sourceReference: '' }).description).not.toContain('Source:');
  });
});

describe('validateGenerated', () => {
  it('accepts a complete case', () => {
    expect(validateGenerated(base)).toEqual({});
  });

  it('requires a summary, a step and an expected result', () => {
    expect(validateGenerated({ ...base, summary: ' ', steps: [' '], expectedResult: '' })).toEqual({
      summary: 'Summary is required',
      steps: 'Add at least one step',
      expectedResult: 'Expected result is required',
    });
  });

  it('limits the summary length', () => {
    expect(validateGenerated({ ...base, summary: 'x'.repeat(201) }).summary).toContain('200');
  });
});

describe('splitLines', () => {
  it('trims lines and drops blanks', () => {
    expect(splitLines('a\r\n  \n b \n\nc')).toEqual(['a', 'b', 'c']);
  });
});
