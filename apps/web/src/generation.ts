import { AI_TAG, type GeneratedCase, type TestCaseInput } from '@qalynks/shared';

/** The seven review columns, in the required order. */
export const REVIEW_COLUMNS = [
  'TC ID',
  'Module',
  'Summary',
  'Steps',
  'Test Data',
  'Expected Result',
  'Actual Result',
] as const;

/**
 * Maps a reviewed generated case onto the existing test case model:
 * Summary -> title, Steps -> ordered steps, Test Data -> testData,
 * Expected Result -> expectedResult, Actual Result -> actualResult (blank).
 * The TC ID is assigned by the server when the case is saved.
 */
export function toTestCaseInput(generated: GeneratedCase): TestCaseInput {
  const notes = ['Generated by AI from requirement text and approved by a reviewer.'];
  if (generated.sourceReference) notes.push(`Source: ${generated.sourceReference}`);
  if (generated.flags.expectedResultNeedsClarification) {
    notes.push(`Needs clarification: ${generated.flags.clarificationNote}`);
  }
  return {
    title: generated.summary.trim(),
    description: notes.join('\n'),
    preconditions: '',
    testData: generated.testData.trim(),
    steps: generated.steps.map((action) => ({ action: action.trim(), expectedResult: '' })),
    expectedResult: generated.expectedResult.trim(),
    actualResult: '',
    priority: generated.priority,
    testType: generated.testType,
    module: generated.module.trim(),
    tags: [AI_TAG, generated.scenarioType],
    status: 'Draft',
  };
}

export function validateGenerated(generated: GeneratedCase): Record<string, string> {
  const errors: Record<string, string> = {};
  if (!generated.summary.trim()) errors.summary = 'Summary is required';
  else if (generated.summary.trim().length > 200)
    errors.summary = 'Summary must be 200 characters or fewer';
  if (generated.steps.filter((s) => s.trim()).length === 0) errors.steps = 'Add at least one step';
  if (!generated.expectedResult.trim()) errors.expectedResult = 'Expected result is required';
  return errors;
}

export function splitLines(text: string): string[] {
  return text
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter(Boolean);
}
